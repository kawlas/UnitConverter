import { createHash } from "node:crypto";
import { readdir, readFile, writeFile } from "node:fs/promises";
import { dirname, extname, join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

const projectRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const distDirectory = join(projectRoot, "dist");
const workerFile = join(distDirectory, "sw.js");
const shellFiles = new Set([
  "404.html",
  "apple-touch-icon.png",
  "manifest.webmanifest",
  "pwa-192.png",
  "pwa-512.png",
]);

const listFiles = async (directory) => {
  const files = [];
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const path = join(directory, entry.name);
    if (entry.isDirectory()) files.push(...await listFiles(path));
    else files.push(path);
  }
  return files;
};

const toPublicUrl = (file) => {
  const path = relative(distDirectory, file).split(sep).join("/");
  if (path === "index.html") return "/";
  if (path.endsWith("/index.html")) return `/${path.slice(0, -"/index.html".length)}`;
  return `/${path}`;
};

const files = (await listFiles(distDirectory))
  .filter((file) => {
    if (file === workerFile) return false;
    const path = relative(distDirectory, file).split(sep).join("/");
    return extname(file) === ".html" || path.startsWith("assets/") || shellFiles.has(path);
  })
  .sort();
const urls = files.map(toPublicUrl);
const versionHash = createHash("sha256");
for (const file of files) {
  versionHash.update(toPublicUrl(file));
  versionHash.update(await readFile(file));
}
const cacheName = `q-converter-${versionHash.digest("hex").slice(0, 12)}`;

const source = `/* Generated by scripts/generate-service-worker.mjs. */
const CACHE_PREFIX = "q-converter-";
const CACHE_NAME = ${JSON.stringify(cacheName)};
const PRECACHE_URLS = ${JSON.stringify(urls, null, 2)};

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches.open(CACHE_NAME)
      .then((cache) => cache.addAll(PRECACHE_URLS))
      .then(() => self.skipWaiting()),
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys()
      .then((names) => Promise.all(names
        .filter((name) => name.startsWith(CACHE_PREFIX) && name !== CACHE_NAME)
        .map((name) => caches.delete(name))))
      .then(() => self.clients.claim()),
  );
});

const canonicalPathname = (pathname) => {
  const legacyAlias = pathname.match(/^\\/convert\\/([^/]+)\\/?$/);
  if (legacyAlias) return "/" + legacyAlias[1];
  return pathname.length > 1 && pathname.endsWith("/") ? pathname.slice(0, -1) : pathname;
};

const canonicalRequest = (request) => {
  const url = new URL(request.url);
  return new Request(url.origin + canonicalPathname(url.pathname), { headers: request.headers });
};

const handleNavigation = async (request) => {
  const cache = await caches.open(CACHE_NAME);
  const cacheKey = canonicalRequest(request);
  try {
    const response = await fetch(request);
    if (response.ok) await cache.put(cacheKey, response.clone());
    return response;
  } catch {
    return await cache.match(cacheKey, { ignoreSearch: true })
      ?? await cache.match("/404.html")
      ?? Response.error();
  }
};

const handleAsset = async (request) => {
  const cached = await caches.match(request, { ignoreSearch: true });
  if (cached) return cached;
  return fetch(request);
};

self.addEventListener("fetch", (event) => {
  const { request } = event;
  const url = new URL(request.url);
  if (request.method !== "GET" || url.origin !== self.location.origin) return;
  event.respondWith(request.mode === "navigate" ? handleNavigation(request) : handleAsset(request));
});
`;

await writeFile(workerFile, source, "utf8");
console.log(`Generated ${relative(projectRoot, workerFile)} with ${urls.length} precached URLs (${cacheName}).`);
